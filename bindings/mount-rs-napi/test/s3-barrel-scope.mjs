const source = process.env.MOUNTX_SOURCE
if (!source) {
  console.log("mount-rs N-API S3 barrel scope: SKIP (MOUNTX_SOURCE is unset)")
  process.exit(0)
}

const oracle = await import(pathToFileURL(resolve(source, "src/s3/index.ts")).href)
const require = createRequire(import.meta.url)
const current = require("@mount-rs/core/s3")
const root = require("@mount-rs/core")
const oracleKeys = Object.keys(oracle).sort()
const currentKeys = Object.keys(current).sort()
const missing = oracleKeys.filter((key) => !(key in current))

assert.deepEqual(missing, [...SCOPED_OUT_ORACLE_EXPORTS].sort())
for (const name of [
  "S3BodyStream",
  "S3Server",
  "S3Session",
  "S3StreamRequest",
  "S3StreamResponse",
  "createS3Server",
]) {
  assert.equal(typeof current[name], "function", `${name} must remain in the supported ./s3 facade`)
}
assert.equal(current.S3Server, root.S3Server)
assert.equal(current.S3Session, root.S3Session)
assert.equal(current.createS3Server, root.createS3Server)

console.log(
  `mount-rs N-API S3 barrel scope: PASS (${oracleKeys.length} oracle runtime exports; ` +
    `${currentKeys.length} package exports; ${missing.length} exact Rust-owned names scoped out)`,
)
